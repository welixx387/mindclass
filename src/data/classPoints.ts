/**
 * Очки классов на конец каждого тома — по таблицам «Class Points → Light Novel»
 * на You-Zitsu Wiki (страницы Class 1-A…1-D (1st Year)/Progression и
 * Class 2-A…2-D (2nd Year)/Progression). Там классы названы по стартовой
 * букве: 1-A — класс Сакаянаги, 1-B — Итиносэ, 1-C — Рюэна, 1-D — Хорикиты.
 *
 * Правила сборки:
 *  - берётся последняя запись тома (итог после всех событий тома);
 *  - буква — из колонки Ranking;
 *  - для томов .5 вики отдельных записей не ведёт: там, где между соседними
 *    томами очки не менялись, значения повторяют предыдущий том;
 *  - том 1-7.5 пропущен: между 7 и 8 томом у класса Рюэна списали 100 очков,
 *    и вики не уточняет, к какому тому это относится;
 *  - 2-12: вики даёт классу Рюэна букву B, но B в тот момент у класса
 *    Сакаянаги (1093 > 1030), поэтому у Рюэна C; B он получает в томе 12.5.
 *
 * Администратор может поправить или скрыть любой том в «Админке → Очки классов»:
 * правки хранятся в базе и важнее этих значений.
 */

import type { ClassPointsMap, VolumePoints } from '../lib/classPoints'
import type { ClassLetter } from '../lib/types'

type Cell = [points: number, letter: ClassLetter]

/** Порядок: класс Сакаянаги, Итиносэ, Рюэна, Хорикиты. */
function v(sakayanagi: Cell, ichinose: Cell, ryuen: Cell, horikita: Cell): VolumePoints {
  const s = ([points, letter]: Cell) => ({ points, letter })
  return { sakayanagi: s(sakayanagi), ichinose: s(ichinose), ryuen: s(ryuen), horikita: s(horikita) }
}

